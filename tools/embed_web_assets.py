"""Bundle template/ and static/ into firmware; also runnable without PlatformIO."""
from pathlib import Path
import argparse
import json
import mimetypes


def generate(project, output):
    project, output = Path(project), Path(output)
    lines = ["// Generated by tools/embed_web_assets.py. Do not edit.", "#pragma once"]
    records = []
    mime_types = {
        ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
        ".js": "application/javascript; charset=utf-8", ".json": "application/json",
        ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg", ".ico": "image/x-icon", ".webp": "image/webp",
        ".woff": "font/woff", ".woff2": "font/woff2",
    }
    for folder in ("template", "static"):
        base = project / folder
        if not base.is_dir():
            raise ValueError(f"Missing web asset folder: {base}")
        for path in sorted(base.rglob("*")):
            if not path.is_file() or any(part.startswith(".") for part in path.relative_to(base).parts):
                continue
            if path.is_symlink() or not path.resolve().is_relative_to(base.resolve()):
                raise ValueError(f"Web assets must remain inside {base}: {path}")
            if folder == "template" and path.suffix != ".html":
                continue
            data = path.read_bytes()
            if folder == "template":
                data.decode("utf-8") # Fail the build rather than serve broken templates.
                if b"\0" in data:
                    raise ValueError(f"NUL byte in template: {path}")
            symbol = f"web_asset_{len(records)}"
            lines.append(f"static const uint8_t {symbol}[] PROGMEM = {{")
            for offset in range(0, len(data), 24):
                lines.append("    " + ",".join(str(b) for b in data[offset:offset + 24]) + ",")
            lines.append("    0\n};") # Terminator for template rendering, excluded from HTTP size.
            relative = path.relative_to(project).as_posix()
            mime = mime_types.get(path.suffix.lower()) or mimetypes.guess_type(path.name)[0] or "application/octet-stream"
            records.append(f"    {{{json.dumps('/' + relative)}, {json.dumps(mime)}, {symbol}, {len(data)}, {'true' if folder == 'static' else 'false'}}},")
    lines += ["static const EmbeddedAsset WEB_ASSETS[] = {", *records, "};", ""]
    content = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")


if "Import" in globals():
    Import("env")
    generated = Path(env.subst("$PROJECT_BUILD_DIR")) / env.subst("$PIOENV") / "generated"
    generate(env.subst("$PROJECT_DIR"), generated / "web_assets_generated.h")
    env.Append(CPPPATH=[str(generated)])
elif __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.project, args.output)
